"""Champion strategy: live screen + backtest with the TimesFM P20 volume veto.

This is the FINAL autoresearch champion (iter83, max_holdings=2): the top-500
S&P 500 (SPY) momentum-rotation strategy tuned to maximize worst_year_sharpe
(the minimum annual Sharpe across full years 2015-2025).

Usage:
  python run_champion.py backtest                    # Reproduce the iter83 champion result
  python run_champion.py live                        # Screen the current session
  python run_champion.py live --as-of 2026-06-01     # Screen a specific date
  python run_champion.py live --current-positions positions.csv
  python run_champion.py live --refresh-data         # Force refresh cached data

The champion config is config/research.json (SPY universe, limit 500) and the
tuned parameters are research_params.json (applied via overfit_harness.apply_params_to_config):
  max_holdings=2, ts_mom=10/0, sma=3/50/210, P20 quantile veto (threshold 0.35,
  ctx=256, horizon=21), vol_scaled_weights (lookback 21), conviction tilt
  (weight_tilt=0.17, conf_tilt, conf_tilt_pow=50, vol-adjusted, vol_pow=4),
  fund_weight=0.02, macro=-0.5/-1.0, min_volume=11M, cost=3bps.

backtest mode delegates to overfit_harness.run_benchmark (perturbation off) so
the result is byte-for-byte identical to the autoresearch champion.
live mode reuses the harness veto/sizing helpers (build_veto_mask, _size_weights)
so the live screen uses the exact same P20 veto + conviction-tilt sizing.

S&P 500 holdings auto-update: load_market_context fetches the current constituents
from Wikipedia (cache/sp500_holdings.csv, fresh within 7 days) when etf_ticker==SPY,
so each run sees the latest S&P 500 as it rebalances. TimesFM forecasts for any
NEW symbols must be generated by re-running `python generate_spy_forecasts.py
--quantiles` (it only forecasts missing (symbol, date) pairs; idempotent).
"""
